// Flat list of every documented path, used by the cross-document tests.
export function allRoutes() {
    return API_SECTIONS.flatMap(s => s.routes.map(r => ({ ...r, section: s.id })));
}

// The path with query-string and :param decoration stripped, which is the form
// that appears in README/llms.txt prose. `/api/transactions/older?before=<n>`
// → `/api/transactions/older`.
export function basePath(p) {
    return String(p).split('?')[0];
}

// ─── Renderers ───────────────────────────────────────────────────────────────
//
// Two callers, two class-name conventions (the server-rendered document and the
// SPA have separate stylesheets), so the class names are parameters. The markup
// shape is identical, which is the point: the two /developers documents can
// look different and still cannot say different things.
export function renderSectionList(section, { listClass = 'endpoints' } = {}) {
    const items = section.routes.map(r =>
        `<li><code>${esc(r.method)} ${esc(r.path)}</code> — ${esc(r.summary)}</li>`
    ).join('\n');
    return `<ul class="${esc(listClass)}">\n${items}\n</ul>`;
}

export function findSection(id) {
    const s = API_SECTIONS.find(x => x.id === id);
    if (!s) throw new Error(`api-reference: no section '${id}'. Sections are: ${API_SECTIONS.map(x => x.id).join(', ')}`);
    return s;
}

// section id → rendered <ul>, plus the optional trailing note as a <p>.
export function renderSection(id, opts = {}) {
    const s = findSection(id);
    const list = renderSectionList(s, opts);
    return s.note ? `${list}\n<p>${esc(s.note)}</p>` : list;
}

