// ─── The API route table — ONE copy, three renderers ─────────────────────────
//
// Audit F-154 (and F-060 before it). The public route list used to exist as
// four hand-maintained copies: README.md, public/llms.txt, the DEVELOPERS_HTML
// string constant in server.js, and renderDevelopersPage() in script.js. They
// drifted in exactly the way four copies always drift — the two that a human
// reads while writing docs (README, llms.txt) stayed current, and the two that
// a *visitor* reads (`/developers`, hard-loaded or via in-app navigation) went
// stale. At the point the finding was written, `/developers` was missing
// community labels, on-chain identity, proxies, multisigs, analytics,
// extrinsic-by-hash, /api/version and /api/health: eight route families that
// exist, are public, are documented elsewhere, and were invisible to anyone
// who followed the site's own "Developers" link.
//
// That is worse than an omission. An integrator who reads /developers and
// concludes "there is no way to resolve an extrinsic hash" writes a block
// scanner instead of calling /api/extrinsic-by-hash/:txHash — the docs cost
// them a feature and cost us the RPC load.
//
// So the endpoint list lives here, once, and both /developers renderers build
// their markup from it. Adding a route means adding one entry; there is no
// second place to forget. test/api-reference.test.js additionally asserts that
// every path in this table appears in public/llms.txt and README.md, so the two
// documents that are still prose cannot silently fall behind either.
//
// This is deliberately NOT generated by walking Express's router at runtime:
//   * the SPA copy runs in a browser with no access to the Express app;
//   * a generated list would publish every internal and operator-only route
//     (/api/diag/*, the email token endpoints) the moment someone registered
//     one, which is a disclosure decision, not a docs decision.
// A curated table that both renderers share fixes the drift without either
// problem. The trade is that a NEW route still has to be added here by hand —
// what changed is that there is exactly one hand to move, and a test that says
// so when the prose docs disagree.

// Escaping is done here rather than by the callers, because the two callers
// have different escapers (server.js has none; script.js has
// stakingEscapeHtml) and "which one did this string go through" is precisely
// the question that produces an XSS. Everything in this file is authored by
// us, so this is defence in depth rather than a live sink — but the renderer
// is the thing that gets copied into the next page, so it escapes.
function esc(s) {
    return String(s == null ? '' : s)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

// ─── The 503 the RPC-dependent endpoints actually send (audit F-155) ─────────
//
// The docs used to promise `{ "error": "rpc not connected" }` — a string
// requireRpc() has never sent. A client written against the documented literal
// treats every RPC outage as an unrecognised error: no backoff, no retry, and
// an unhelpful message in front of the user. README and llms.txt were
// corrected in round 1; the two /developers copies were not, so the wrong
// literal survived on the page most integrators actually read.
//
// Exporting the envelope means requireRpc() in server.js and the reference
// pages render from the same object. The docs cannot describe a response the
// server does not send, because there is only one description.
//
// `code` is the stable part. The prose in `error` is written for a human and
// is reworded freely; that is why the docs tell clients to branch on `code`
// (or simply on the 503 status) and never on the message.
export const RPC_NOT_READY = {
    code: 'RPC_NOT_READY',
    error: 'Live blockchain data is not available right now — the explorer is still connecting to the Polkadex node. Please refresh in a few seconds.'
};

// The JSON body as an integrator sees it, for embedding in a <pre> block.
export function rpcNotReadyExample() {
    return JSON.stringify({ error: RPC_NOT_READY.error, code: RPC_NOT_READY.code }, null, 2);
}

