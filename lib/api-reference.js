// Short label for the table of contents; falls back to the heading.
export function tocLabel(entry) {
    return entry.toc || entry.title;
}

// The table of contents, in outline order. Both renderers emit this, so a
// section added to DOC_OUTLINE appears in both TOCs or neither.
export function renderToc({ navClass = 'toc' } = {}) {
    const links = DOC_OUTLINE
        .map(e => `<a href="#${esc(e.id)}">${esc(tocLabel(e))}</a>`)
        .join('\n            ');
    return `<nav class="${esc(navClass)}" aria-label="On this page">\n            ${links}\n        </nav>`;
}

// Walk the outline, asking the caller for each section's body.
//
//   bodyFor(entry) -> HTML string, or '' / null to emit the heading alone
//
// The heading and its `id` are produced HERE rather than by the caller. That is
// the whole mechanism: a renderer physically cannot ship a section without an
// anchor, or with a heading that differs from the other renderer's.
export function renderOutline(bodyFor, { headingTag = 'h2', sectionClass = '' } = {}) {
    const cls = sectionClass ? ` class="${esc(sectionClass)}"` : '';
    return DOC_OUTLINE.map(entry => {
        const body = bodyFor(entry) || '';
        return `<section${cls} id="${esc(entry.id)}">\n<${headingTag}>${esc(entry.title)}</${headingTag}>\n${body}\n</section>`;
    }).join('\n\n');
}

